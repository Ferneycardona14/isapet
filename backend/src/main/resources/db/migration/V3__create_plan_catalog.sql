CREATE TABLE plan_afiliacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE UNIQUE INDEX uk_plan_afiliacion_codigo_ci
    ON plan_afiliacion (lower(codigo));

CREATE TABLE version_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL,
    precio_mensual NUMERIC(14, 0) NOT NULL,
    maximo_mascotas INTEGER NOT NULL,
    limite_atenciones INTEGER,
    vigente_desde DATE NOT NULL,
    CONSTRAINT fk_version_plan_plan
        FOREIGN KEY (plan_id) REFERENCES plan_afiliacion (id)
        ON DELETE RESTRICT,
    CONSTRAINT uk_version_plan_fecha
        UNIQUE (plan_id, vigente_desde),
    CONSTRAINT ck_version_plan_precio_positivo
        CHECK (precio_mensual > 0),
    CONSTRAINT ck_version_plan_maximo_mascotas_positivo
        CHECK (maximo_mascotas > 0),
    CONSTRAINT ck_version_plan_limite_atenciones_positivo
        CHECK (limite_atenciones IS NULL OR limite_atenciones > 0)
);

CREATE FUNCTION validar_nueva_version_plan()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    ultima_vigencia DATE;
    plan_activo BOOLEAN;
BEGIN
    SELECT activo
    INTO plan_activo
    FROM plan_afiliacion
    WHERE id = NEW.plan_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'El plan asociado no existe.'
            USING ERRCODE = '23503';
    END IF;

    IF NOT plan_activo THEN
        RAISE EXCEPTION 'No se pueden publicar versiones para un plan inactivo.'
            USING ERRCODE = '55000';
    END IF;

    SELECT MAX(vigente_desde)
    INTO ultima_vigencia
    FROM version_plan
    WHERE plan_id = NEW.plan_id;

    IF ultima_vigencia IS NOT NULL AND NEW.vigente_desde < CURRENT_DATE THEN
        RAISE EXCEPTION 'La vigencia de una nueva versión no puede ser anterior a la fecha actual (%).', CURRENT_DATE
            USING ERRCODE = '23514',
                  CONSTRAINT = 'ck_version_plan_not_retroactive';
    END IF;

    IF ultima_vigencia IS NOT NULL AND NEW.vigente_desde <= ultima_vigencia THEN
        RAISE EXCEPTION 'La versión debe iniciar después de la última vigencia (%).', ultima_vigencia
            USING ERRCODE = '23505',
                  CONSTRAINT = 'ck_version_plan_sequential_dates';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_version_plan_validate_insert
    BEFORE INSERT ON version_plan
    FOR EACH ROW
    EXECUTE FUNCTION validar_nueva_version_plan();

CREATE FUNCTION impedir_modificacion_version_plan()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'Las versiones comerciales publicadas son inmutables.'
        USING ERRCODE = '55000';
END;
$$;

CREATE TRIGGER trg_version_plan_immutable
    BEFORE UPDATE OR DELETE ON version_plan
    FOR EACH ROW
    EXECUTE FUNCTION impedir_modificacion_version_plan();

WITH planes_iniciales AS (
    INSERT INTO plan_afiliacion (codigo, nombre)
    VALUES
        ('BASICO', 'Básico'),
        ('ESTANDAR', 'Estándar'),
        ('PREMIUM', 'Premium')
    RETURNING id, codigo
)
INSERT INTO version_plan (
    plan_id,
    precio_mensual,
    maximo_mascotas,
    limite_atenciones,
    vigente_desde
)
SELECT
    id,
    CASE codigo
        WHEN 'BASICO' THEN 60000
        WHEN 'ESTANDAR' THEN 100000
        WHEN 'PREMIUM' THEN 250000
    END,
    CASE codigo
        WHEN 'BASICO' THEN 1
        WHEN 'ESTANDAR' THEN 2
        WHEN 'PREMIUM' THEN 4
    END,
    CASE codigo
        WHEN 'BASICO' THEN 2
        WHEN 'ESTANDAR' THEN 4
        WHEN 'PREMIUM' THEN NULL
    END,
    CURRENT_DATE
FROM planes_iniciales;
